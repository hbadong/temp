def parse_chars(s, name):
    pat = re.compile(r'(?<![A-Za-z_])' + re.escape(name) + r'(?:\.concat\(| = )\[')
    chars = set()
    for m in pat.finditer(s):
        i = s.find('[', m.start())
        depth, j = 0, i
        instr = esc = False
        while j < len(s):
            ch = s[j]
            if esc: esc = False
            elif ch == '\\': esc = True
            elif ch == '"': instr = not instr
            elif not instr:
                if ch == '[': depth += 1
                elif ch == ']':
                    depth -= 1
                    if depth == 0: break
            j += 1
        chars |= set(re.findall(r'\{c:"([^"]+)"', s[i:j]))
    return chars


